# ---------------------------------------------------------------- leakage test
FAR = 4_102_444_800   # year 2100, "has not ended yet"

def truncate_events(ev, T):
    """What a live system would know at time T: events that started after T do not exist,
    and alerts still running at T have no end time."""
    t = int(to_sec([T])[0])
    def cut(s, e):
        m = s <= t
        return s[m], np.where(e[m] > t, FAR, e[m])
    return {"kyiv": cut(*ev["kyiv"]),
            "regions": {k: cut(*v) for k, v in ev["regions"].items()},
            "data_end": T}

def leakage_check(ev, cfg, n_checks=5, seed=0):
    rng = np.random.default_rng(seed)
    end = ev["data_end"].floor(f"{cfg['bin_minutes']}min")
    for _ in range(n_checks):
        T = end - pd.Timedelta(minutes=cfg["bin_minutes"] * int(rng.integers(0, 60 * 24 * 6)))
        grid = pd.date_range(T - pd.Timedelta(days=5), T, freq=f"{cfg['bin_minutes']}min")
        full = build_features(ev, grid, cfg)
        trunc = build_features(truncate_events(ev, T), grid, cfg)
        pd.testing.assert_frame_equal(full, trunc, check_exact=False, rtol=1e-9, atol=1e-9)
    print(f"✅ leakage check passed: features at T are identical when all data after T is deleted ({n_checks} random T)")

leakage_check(events, CFG)

def make_dataset(ev, cfg):
    b, H = cfg["bin_minutes"], cfg["horizon_min"]
    t0 = pd.Timestamp(cfg["train_start"])
    last_T = (ev["data_end"] - pd.Timedelta(minutes=H)).floor(f"{b}min")   # label must be fully observed
