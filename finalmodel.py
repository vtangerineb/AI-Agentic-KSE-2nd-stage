"""## How to read the results honestly
* Compare to the **baselines**, not to 0 or 1. `lift` close to 1 means the model has no skill beyond the base rate.
* Look at all four folds. A single 30-day window can contain one or two big attack waves and move F1 a lot.
* Precision/recall depend strongly on the horizon: shorter horizons (30 min) are easier because neighbouring oblasts alert first; long horizons approach "will there be an attack tonight", which is mostly about attack rhythm.
* The remaining ceiling comes from information that is not in the alert history. Text/media signals (above) are the realistic next step.

## Chance of a new Kyiv alert in the next hour
"""

from sklearn.isotonic import IsotonicRegression

AS_OF = "2026-09-05 21:30"        # None = now (UTC). To replay a past moment use e.g. AS_OF = "2026-09-05 21:30"  (UTC)
MAX_STALE_H = 6     # data ends longer ago than this -> "now" is unknown -> use the last moment the data covers

def kyiv_forecast(events, ds, feats, cfg, as_of=None, max_stale_h=6):
    b, H = cfg["bin_minutes"], cfg["horizon_min"]
    now = pd.Timestamp.now(tz="UTC").tz_localize(None)
    data_end = events["data_end"]
    note = ""
    if as_of is not None:
        T = pd.Timestamp(as_of).floor(f"{b}min")
        ev = truncate_events(events, T)                      # replay: pretend nothing after T exists
    else:
        T, ev = now.floor(f"{b}min"), events
        if now - data_end > pd.Timedelta(hours=max_stale_h):
            T = data_end.floor(f"{b}min")
            note = (f"The data ends at {data_end:%Y-%m-%d %H:%M} UTC, which is {(now - data_end).total_seconds()/3600:.0f} h before now,\n"
                    "so the live state is unknown. Showing the last moment the data covers. Refresh the data (or plug in a live feed) for 'now'.")

    # same protocol as the evaluated folds: train on old data, tune on the latest val_days, labels fully known at T
    cutoff = T - pd.Timedelta(minutes=H)
    val_start = cutoff - pd.Timedelta(days=cfg["val_days"])
    tr = ds[ds.index <= val_start - pd.Timedelta(minutes=H)]
    va = ds[(ds.index > val_start) & (ds.index <= cutoff)]
    if len(tr) < 5000 or va["y"].sum() == 0:
        raise ValueError("not enough labelled history before that moment")
    age = np.asarray((val_start - tr.index) / pd.Timedelta(days=1), dtype=float)
    model = make_xgb(SEARCH_GRID[1], cfg)
    model.fit(tr[feats], tr["y"], sample_weight=0.5 ** (age / 180))
    p_va = model.predict_proba(va[feats])[:, 1]
    iso = IsotonicRegression(out_of_bounds="clip", y_min=0.0, y_max=1.0).fit(p_va, va["y"])

    # features for the single moment T (uses only information available at T)
    grid = pd.date_range(T - pd.Timedelta(days=5), T, freq=f"{b}min")
    row = build_features(ev, grid, cfg).iloc[[-1]]
    local = T.tz_localize("UTC").tz_convert("Europe/Kyiv")
    pretty = lambda c, p: c[len(p):].replace("_oblast", "").replace("_", " ").title()
    under_alert = [pretty(c, "act_") for c in row.columns if c.startswith("act_") and row[c].iloc[0] == 1]
    near = [c for c in row.columns if c.startswith("act_") and any(st in c for st in GROUPS["near"])]
    out = dict(T_utc=T, T_local=local, active=bool(row["kyiv_active"].iloc[0] == 1), note=note,
               under_alert=under_alert, near_active=int(row[near].sum(axis=1).iloc[0]) if near else 0)

    print("=" * 62)
    print(f" Kyiv air-alert outlook   as of {local:%Y-%m-%d %H:%M} Kyiv time  ({T:%H:%M} UTC)")
    print("=" * 62)
    if note:
        print("⚠ ", note.replace("\n", "\n   "))
    if out["active"]:
        mins = float(row["kyiv_min_since_start"].iloc[0])
        print(f" An alert is ALREADY ACTIVE in Kyiv (running for {mins:.0f} min). The model forecasts the start of a NEW alert,")
        print(" so it gives no probability while one is running.")
        return out

    p_raw = float(model.predict_proba(row[feats])[0, 1])
    p = float(iso.predict([p_raw])[0])
    pct = float((p_va < p_raw).mean())
    band = ("VERY HIGH" if pct >= 0.97 else "HIGH" if pct >= 0.88 else "MODERATE" if pct >= 0.70 else "LOW")
    typical = ds[(ds.index >= T - pd.Timedelta(days=60)) & (np.floor(ds["local_hour"]) == local.hour)]["y"].mean()
    out.update(prob=p, band=band, percentile=pct, typical_for_hour=float(typical))

    print(f" Chance a NEW alert starts in Kyiv within the next {H} min:  ≈ {p:.0%}   [{band} relative risk]")
    print(f"   riskier than {pct:.0%} of moments in the last {cfg['val_days']} days;"
          f"  typical for {local.hour:02d}:xx lately: {typical:.0%}")
    print(f" Right now: {len(under_alert)} oblast(s) under alert" + (f": {', '.join(under_alert)}" if under_alert else ""))
    print(f"   near-Kyiv oblasts under alert: {out['near_active']} of {len(near)}")
    print(f" Last Kyiv alert ended {float(row['kyiv_min_since_end'].iloc[0]):.0f} min ago;"
          f"  Kyiv alerts started in the last 24 h: {int(row['kyiv_starts_24h'].iloc[0])}")
    print("-" * 62)
    print(" Probability is approximate (calibrated on the last validation block); it is a risk")
    print(" estimate from alert history only, not a warning system. Always follow official alerts.")
    return out

forecast = kyiv_forecast(events, ds, FEATS, CFG, as_of=AS_OF, max_stale_h=MAX_STALE_H)

