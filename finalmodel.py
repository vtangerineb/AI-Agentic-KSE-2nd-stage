def ensure_dataset(path, refresh, timeout=15):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    have = os.path.exists(path) and os.path.getsize(path) > 1000
    if have and not refresh:
        return path
    try:
        api = "https://api.github.com/repos/Vadimkin/ukrainian-air-raid-sirens-dataset/contents/datasets"
        r = requests.get(api, timeout=timeout); r.raise_for_status()
        csvs = [f for f in r.json() if f["name"].lower().endswith(".csv")]
        official = [f for f in csvs if "official" in f["name"].lower()]
        english = [f for f in official if "_en" in f["name"].lower()]
        pick = (english or official or csvs)[0]
        res = requests.get(pick["download_url"], timeout=timeout); res.raise_for_status()
        if len(res.content) < 1000:
            raise RuntimeError("downloaded file is suspiciously small")
        with open(path, "wb") as f:
            f.write(res.content)
        print("Downloaded", pick["name"])
    except Exception as e:
        if have:
            print(f"[warn] refresh failed ({type(e).__name__}); using cached {path}")
        else:
            raise
    return path

def to_sec(x):
    """datetime-like -> int64 seconds since epoch (naive UTC)."""
    return pd.DatetimeIndex(x).values.astype("datetime64[s]").astype(np.int64)

KYIV_EXCLUDE = ("oblast", "область", "kyivska", "київська")
def is_kyiv_city(name):
    return (("kyiv" in name) or ("київ" in name)) and not any(k in name for k in KYIV_EXCLUDE)

def load_events(path):
    df = pd.read_csv(path)
    if "source" in df.columns and (df["source"].astype(str).str.lower() == "official").any():
        df = df[df["source"].astype(str).str.lower() == "official"]
    for c in ("started_at", "finished_at"):
        df[c] = pd.to_datetime(df[c], errors="coerce", utc=True).dt.tz_localize(None)
    df = df.dropna(subset=["started_at"])
    data_end = max(df["started_at"].max(), df["finished_at"].max())
    df["finished_at"] = df["finished_at"].fillna(data_end)       # still-running alerts
    df = df[df["finished_at"] >= df["started_at"]]
    df["name"] = df["oblast"].astype(str).str.strip().str.lower()
    df = df.sort_values("started_at", kind="stable")

    kmask = df["name"].map(is_kyiv_city)
    if not kmask.any():
        raise ValueError("Kyiv city not found. Region names: %s" % sorted(df["name"].unique()))
    kyiv = df[kmask]
    events = {
        "kyiv": (to_sec(kyiv["started_at"]), to_sec(kyiv["finished_at"])),
        "regions": {n: (to_sec(g["started_at"]), to_sec(g["finished_at"]))
                    for n, g in df[~kmask].groupby("name")},
        "data_end": data_end,
    }
    print(f"Kyiv-city rows matched on: {sorted(kyiv['name'].unique())}  ({len(kyiv)} alerts)")
    print(f"Other regions: {len(events['regions'])}; data from {df['started_at'].min()} to {data_end} (UTC)")
    return events

