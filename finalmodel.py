def active_count(s, e, G):
    """number of intervals [s,e) covering grid time G (started and not yet ended at G)."""
    N = len(G)
    diff = np.zeros(N + 1, dtype=np.int32)
    np.add.at(diff, np.searchsorted(G, s, side="left"), 1)
    np.add.at(diff, np.searchsorted(G, e, side="left"), -1)
    return np.cumsum(diff[:N])

def active_flags(s, e, G):
    return (active_count(s, e, G) > 0).astype(np.int8)

def count_in_window(s, G, lo, hi):
    """number of event starts in (G-lo, G-hi]   (lo >= hi >= 0, seconds)."""
    return np.searchsorted(s, G - hi, side="right") - np.searchsorted(s, G - lo, side="right")

def build_features(ev, grid, cfg):
    """Features for forecast times `grid`. Row T uses ONLY information available at T."""
    G = to_sec(grid); N = len(G); b = cfg["bin_minutes"]; Hs = cfg["horizon_min"] * 60
    out = {}

    # ---- Kyiv alert history
    ks, ke = ev["kyiv"]
    out["kyiv_active"] = active_flags(ks, ke, G)
    j = np.searchsorted(ks, G, side="right") - 1
    out["kyiv_min_since_start"] = np.where(j >= 0, (G - ks[np.maximum(j, 0)]) / 60.0, CAP_MIN)
    order = np.argsort(ke, kind="stable")
    kes, kdur = ke[order], ((ke - ks)[order]) / 60.0
    jj = np.searchsorted(kes, G, side="right") - 1          # only alerts that have ENDED by T
    out["kyiv_min_since_end"] = np.where(jj >= 0, (G - kes[np.maximum(jj, 0)]) / 60.0, CAP_MIN)
    out["kyiv_last_dur_min"] = np.where(jj >= 0, kdur[np.maximum(jj, 0)], np.nan)
    for nm, w in (("1h", 3600), ("3h", 10800), ("6h", 21600), ("24h", 86400), ("7d", 604800)):
        out[f"kyiv_starts_{nm}"] = count_in_window(ks, G, w, 0)
    out["kyiv_starts_window_1d_ago"] = count_in_window(ks, G, 86400, 86400 - Hs)
    out["kyiv_starts_window_7d_ago"] = count_in_window(ks, G, 604800, 604800 - Hs)

    # ---- other regions
    names = sorted(ev["regions"])
    R = len(names)
    A = np.zeros((N, R), dtype=np.int8)
    C = np.zeros((N, R), dtype=np.int16)          # how many raion/hromada-level alerts are active
    SINCE = np.full((N, R), 360.0, dtype=np.float32)   # minutes since the region's latest alert start (cap 6h)
    S = {w: np.zeros((N, R), dtype=np.int8) for w in (1800, 3600, 10800)}
    for i, n in enumerate(names):
        s, e = ev["regions"][n]
        if len(s) == 0:
            continue
        C[:, i] = active_count(s, e, G)
        A[:, i] = C[:, i] > 0
        jr = np.searchsorted(s, G, side="right") - 1
        SINCE[:, i] = np.where(jr >= 0, np.minimum((G - s[np.maximum(jr, 0)]) / 60.0, 360.0), 360.0)
        for w in S:
            S[w][:, i] = count_in_window(s, G, w, 0) > 0
    nat = A.sum(1)
    out["nat_active"] = nat
    out["nat_started_30m"] = S[1800].sum(1)
    out["nat_started_1h"] = S[3600].sum(1)
    out["nat_started_3h"] = S[10800].sum(1)
    nat_s = pd.Series(nat, index=grid)
    for m in (30, 60, 180):
        out[f"nat_active_chg_{m}m"] = (nat_s - nat_s.shift(m // b)).values
    out["nat_max_6h"] = nat_s.rolling(6 * 60 // b).max().values
    out["nat_max_24h"] = nat_s.rolling(24 * 60 // b).max().values
    out["nat_mean_24h"] = nat_s.rolling(24 * 60 // b).mean().values
    out["nat_max_72h"] = nat_s.rolling(72 * 60 // b).max().values

    for g, stems in GROUPS.items():
        idx = [i for i, n in enumerate(names) if any(st in n for st in stems)]
        out[f"grp_{g}_active"] = A[:, idx].sum(1) if idx else np.zeros(N)
        out[f"grp_{g}_started_1h"] = S[3600][:, idx].sum(1) if idx else np.zeros(N)
        out[f"grp_{g}_units"] = C[:, idx].sum(1) if idx else np.zeros(N)   # intensity, not just on/off

    used = set()
    for i, n in enumerate(names):
        safe = re.sub(r"[^a-z0-9]+", "_", n).strip("_") or f"r{i}"
        if safe in used: safe = f"{safe}_{i}"
        used.add(safe)
        out[f"act_{safe}"] = A[:, i]
        out[f"since_{safe}"] = SINCE[:, i]

    # ---- local (Kyiv) time
    loc = pd.DatetimeIndex(grid).tz_localize("UTC").tz_convert("Europe/Kyiv")
    h = loc.hour.values + loc.minute.values / 60.0
    out["local_hour"] = h
    out["hour_sin"], out["hour_cos"] = np.sin(2*np.pi*h/24), np.cos(2*np.pi*h/24)
    dow = loc.dayofweek.values
    out["dow_sin"], out["dow_cos"] = np.sin(2*np.pi*dow/7), np.cos(2*np.pi*dow/7)
    out["is_weekend"] = (dow >= 5).astype(int)
    return pd.DataFrame(out, index=grid)

def make_labels(kyiv_starts, grid, horizon_min):
    """1 if a Kyiv alert STARTS in (T, T+H].  This is the target, never a feature."""
    G = to_sec(grid); Hs = horizon_min * 60
    return ((np.searchsorted(kyiv_starts, G + Hs, side="right")
             - np.searchsorted(kyiv_starts, G, side="right")) > 0).astype(int)

