# ---------------------------------------------------------------- training / evaluation
def pick_thresholds(y, score, target_recall):
    if y.sum() == 0:
        raise ValueError("validation block has no positives")
    pr, rc, th = precision_recall_curve(y, score)
    f1 = 2 * pr * rc / np.clip(pr + rc, 1e-12, None)
    t_f1 = th[int(np.argmax(f1[:-1]))]
    ok = np.where(rc[:-1] >= target_recall)[0]
    t_rec = th[ok[-1]] if len(ok) else th[0]
    return float(t_f1), float(t_rec)

def event_recall(y, pred, T_index, onsets):
    """share of Kyiv alert onsets for which at least one alarm fired in the H minutes before it."""
    pos = y == 1
    if pos.sum() == 0:
        return np.nan
    nxt = np.searchsorted(onsets, to_sec(T_index[pos]), side="right")
    return float(pd.Series(pred[pos]).groupby(nxt).max().mean())

def evaluate(method, y, score, thr, T_index, onsets, cfg):
    pred = (score >= thr).astype(int)
    tp = int(((pred == 1) & (y == 1)).sum()); fp = int(((pred == 1) & (y == 0)).sum())
    fn = int(((pred == 0) & (y == 1)).sum())
    prec = tp / max(tp + fp, 1); rec = tp / max(tp + fn, 1)
    base = float(y.mean())
    ap = float(average_precision_score(y, score)) if np.ptp(score) > 0 else base
    return dict(method=method, thr=thr, precision=prec, recall=rec,
                f1=2 * prec * rec / max(prec + rec, 1e-12), ap=ap, base_rate=base,
                lift=ap / base if base > 0 else np.nan, alarm_frac=float(pred.mean()),
                alarm_h_per_day=float(pred.sum() * cfg["bin_minutes"] / 60 / cfg["test_days"]),
                event_recall=event_recall(y, pred, T_index, onsets))

SEARCH_GRID = [
    dict(max_depth=2, n_estimators=200, learning_rate=0.05, min_child_weight=50),
    dict(max_depth=3, n_estimators=300, learning_rate=0.03, min_child_weight=50),
    dict(max_depth=4, n_estimators=300, learning_rate=0.03, min_child_weight=20),
]
HALFLIVES = [60, 180, None]     # recency weighting of training rows (days)

def make_xgb(p, cfg):
    # fixed number of trees: early stopping on a single validation block stopped after 2-24 trees in v2
    return xgb.XGBClassifier(subsample=0.8, colsample_bytree=0.7, reg_lambda=10.0, tree_method="hist",
                             random_state=cfg["seed"], n_jobs=-1, **p)

def run_fold(ds, ev, test_start, test_end, cfg):
    H = pd.Timedelta(minutes=cfg["horizon_min"])
    val_start = test_start - pd.Timedelta(days=cfg["val_days"])
    ix = ds.index
    tr = ds[ix <= val_start - H]                              # purge: labels end before val_start
    va = ds[(ix >= val_start) & (ix <= test_start - H)]        # purge: labels end before test_start
    te = ds[(ix >= test_start) & (ix < test_end)]
    onsets = ev["kyiv"][0]
    age = np.asarray((val_start - tr.index) / pd.Timedelta(days=1), dtype=float)
    halflives = HALFLIVES if cfg["search"] else [cfg["halflife_days"]]
    grid = SEARCH_GRID if cfg["search"] else SEARCH_GRID[1:2]
    best = None
    for hl in halflives:
        w = (0.5 ** (age / hl)) if hl else None
        for params in grid:
            m = make_xgb(params, cfg)
            m.fit(tr[FEATS], tr["y"], sample_weight=w)
            ap_va = average_precision_score(va["y"], m.predict_proba(va[FEATS])[:, 1])
            if best is None or ap_va > best[0]:
                best = (ap_va, m, hl, params)
    val_ap, model, hl, params = best                      # chosen on validation only
    p_va = model.predict_proba(va[FEATS])[:, 1]
    p_te = model.predict_proba(te[FEATS])[:, 1]
    t_f1, t_rec = pick_thresholds(va["y"].values, p_va, cfg["target_recall"])
    t_alarm = float(np.quantile(p_va, 1 - cfg["target_alarm_frac"]))

    rows = [evaluate("XGB @ best-F1 thr", te["y"].values, p_te, t_f1, te.index, onsets, cfg),
            evaluate(f"XGB @ recall>={cfg['target_recall']:.0%}", te["y"].values, p_te, t_rec, te.index, onsets, cfg),
            evaluate(f"XGB @ alarm~{cfg['target_alarm_frac']:.0%} of time", te["y"].values, p_te, t_alarm, te.index, onsets, cfg)]
    # baselines (same protocol: threshold picked on validation)
    clim = tr.groupby(np.floor(tr["local_hour"]))["y"].mean()
    base_scores = {
        "baseline: hour-of-day rate": lambda d: np.floor(d["local_hour"]).map(clim).fillna(tr["y"].mean()).values,
        "baseline: #oblasts under alert": lambda d: d["nat_active"].values.astype(float),
        "baseline: near-oblasts under alert": lambda d: d["grp_near_active"].values.astype(float),
    }
    for nm, fn in base_scores.items():
        t, _ = pick_thresholds(va["y"].values, fn(va), cfg["target_recall"])
        rows.append(evaluate(nm, te["y"].values, fn(te), t, te.index, onsets, cfg))
    rows.append(evaluate("baseline: always alert", te["y"].values, np.zeros(len(te)), -np.inf, te.index, onsets, cfg))

    table = pd.DataFrame(rows)
    info = dict(test_start=test_start, test_end=test_end, n_train=len(tr), n_val=len(va), n_test=len(te),
                n_test_pos=int(te["y"].sum()), chosen=f"depth={params['max_depth']},trees={params['n_estimators']},halflife={hl},val_AP={val_ap:.3f}")
    return dict(table=table, info=info, model=model, y_te=te["y"].values, p_te=p_te, te_index=te.index)

def walk_forward(ds, ev, cfg):
    b = pd.Timedelta(minutes=cfg["bin_minutes"]); td = pd.Timedelta(days=cfg["test_days"])
    t_max = ds.index.max() + b
    res = []
    for k in range(cfg["n_folds"]):
        te_end = t_max - (cfg["n_folds"] - 1 - k) * td
        res.append(run_fold(ds, ev, te_end - td, te_end, cfg))
    return res

